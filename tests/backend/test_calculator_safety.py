"""Security regression: the calculate tool must never eval arbitrary code.

The expression is generated by the query agent from user questions, so it is
attacker-influenceable. Guards against RCE + the exponentiation DoS the old
charset-filtered eval() allowed.
"""
from app.agents.tools.calculator_tools import calculate as _c

def _call(e):
    fn = getattr(_c, "_tool_func", None) or getattr(_c, "__wrapped__", None) or _c
    return fn(e)

def test_legit_arithmetic():
    assert _call("13/39*100") == "33.33"
    assert _call("4*13 + 3*10 + 2*16") == "114"
    assert _call("2**8") == "256"

def test_division_by_zero_handled():
    assert "division by zero" in _call("10/0")

def test_blocks_code_injection():
    for attack in ('__import__("os").system("id")', "[].__class__",
                   'open("/etc/passwd")', "().__class__.__bases__"):
        assert _call(attack).startswith("Error"), attack

def test_blocks_exponent_dos():
    # Must return an error fast, not hang computing a giant int.
    assert "exponent too large" in _call("9**9**9**9")

def test_length_capped():
    assert "too long" in _call("1+" * 200 + "1")
